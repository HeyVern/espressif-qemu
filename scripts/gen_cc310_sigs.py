#!/usr/bin/env python3
"""Generate byte signatures for nrf_cc310 library functions from differently linked MeshCore ELF files.

    scripts/gen_cc310_sigs.py a.elf b.elf c.elf > files/hw/arm/nrf52840_cc310_sigs.h

Bytes that differ between links, such as branch offsets and literal pools, are masked out.
"""
import glob
import struct
import subprocess
import sys
from pathlib import Path

FUNCTIONS = [
    ('CRYS_ECEDW_Verify', 0xe0), ('CRYS_HASH', 0xe1), ('CRYS_HASH_Init', 0xe2), ('CRYS_HASH_Update', 0xe3),
    ('CRYS_HASH_Finish', 0xe4), ('CRYS_HMAC_Init', 0xe5), ('CRYS_HMAC_Update', 0xe6), ('CRYS_HMAC_Finish', 0xe7),
    ('SaSi_AesInit', 0xe8), ('SaSi_AesSetKey', 0xe9), ('SaSi_AesBlock', 0xea), ('SaSi_AesFinish', 0xeb),
    ('SaSi_AesFree', 0xec), ('CRYS_RND_GenerateVector', 0xed),
]
MAX_LEN = 96
NM = glob.glob(str(Path.home() / '.platformio/packages/toolchain-gccarmnoneeabi*/bin/arm-none-eabi-nm'))[0]


def load(elf):
    symbols = {}
    for line in subprocess.check_output([NM, '-S', elf], text=True).splitlines():
        parts = line.split()
        if len(parts) == 4 and parts[2] in 'Tt':
            symbols[parts[3]] = (int(parts[0], 16) & ~1, int(parts[1], 16))
    data = Path(elf).read_bytes()
    phoff, phentsize, phnum = struct.unpack_from('<I', data, 28)[0], *struct.unpack_from('<HH', data, 42)
    segments = []
    for index in range(phnum):
        kind, offset, vaddr, _, filesz = struct.unpack_from('<5I', data, phoff + index * phentsize)
        if kind == 1:
            segments.append((vaddr, offset, filesz))

    def read(address, length):
        for vaddr, offset, filesz in segments:
            if vaddr <= address and address + length <= vaddr + filesz:
                return data[offset + address - vaddr:offset + address - vaddr + length]
        raise KeyError(hex(address))
    return symbols, read


def main():
    builds = [load(elf) for elf in sys.argv[1:]]
    print('// Generated by scripts/gen_cc310_sigs.py; do not edit.')
    print('typedef struct { const char *name; uint8_t svc; uint8_t len; const uint8_t *bytes; const uint8_t *mask; } Cc310Sig;')
    entries = []
    for name, svc in FUNCTIONS:
        size = min(builds[0][0][name][1], MAX_LEN)
        copies = [read(symbols[name][0], size) for symbols, read in builds]
        mask = bytes(0xff if len({copy[i] for copy in copies}) == 1 else 0 for i in range(size))
        symbol = name.lower()
        print('static const uint8_t %s_bytes[] = { %s };' % (symbol, ', '.join('0x%02x' % b for b in copies[0])))
        print('static const uint8_t %s_mask[] = { %s };' % (symbol, ', '.join('0x%02x' % b for b in mask)))
        entries.append('    { "%s", 0x%02x, %d, %s_bytes, %s_mask },' % (name, svc, size, symbol, symbol))
        print('// %s: %d bytes, %d masked' % (name, size, mask.count(0)), file=sys.stderr)
    print('static const Cc310Sig cc310_sigs[] = {')
    print('\n'.join(entries))
    print('};')


main()
